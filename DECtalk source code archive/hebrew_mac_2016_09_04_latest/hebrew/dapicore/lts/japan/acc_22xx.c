/*========== ACC22CV(p,q) ==================================
	機能：複合動詞・複合形容詞のアクセントを決定する

	　前語は平板化し、後語は高く付いて、自身の滝で落ちる
	　但し、後部が平板型動詞のときは、尾高化する。
  ==========================================================*/
void ACC22CV(p,q) integer_16 p; register integer_16 q; {
	register integer_16 qp;
	integer_16 r,bno;

	ACC000H(p);
	qp=phrase_ptr[q];
	if(phrase_kind[q]==pkind_adj_stem){ goto ACC22CV_200; }
	/* 平板型動詞は高く付いて尾高化。*/
	if(chk_heiban(q)){ ACC0002(q); }
ACC22CV_200:
	/* 起伏型動詞・形容詞は高く付いて自分の滝で落ちる。*/
	if(accent0[qp]==1){ accent0[qp]=2; }

	/*
	 *	 複合用言は名詞化するときは平板化することが多い。
	 * また、動詞化するときは尾高化することが多い。
	 *	 それゆえに、後の用言の後端番号のひとつめを調べて、
	 * その用言が名詞かどうかを調べる。
	 *	（例）　動き始めは　…　名詞
	 *			動き始めた　…　動詞
	 *			動き始めて　…　動詞
	 */
	if(r=next_phrase(q)){
		--r;
		/*
		 * rは次の文節の直前の要素を指す。
		 * 「動き出し」のときは「し」。r=q+1
		 * 「動き始め」のときは「始め」。r=q
		 */
		for(bno=0;bno<stc_nbno[r];++bno){
			if(bno=stc_bno[r][bno]){ goto ACC22CV_590; }
		}
	}
ACC22CV_590:
	/*
	 * 「動き始めが」、「動き始めは」の「始め」の後端番号は７である。
	 * 「動き始める」、「動き始めた」の「始め」の後端番号は４７である。
	 * 後端番号が７のときは体言形とみなし、４７のときは用言形とみなす。
	 */
	if(bno_tbl[bno]==pkind_noun){
		/* 体言形ならば、平板化する。*/
		ACC0005(q);
	}
}

