/*========== ACC2221(q) =====================================================
	機能：ｑ番目の要素は２１型の結合をする

	　第１拍は高くなり、第２アクセントの滝で落ちる。
	第２アクセントがないときは、
	平板型のときは、第２アクセント＝１
	それ以外は、第２アクセント＝第１アクセント、とする。(89/1/10)
  ==============================================================================*/
void ACC2221(q) integer_16 q; {
	register integer_16 qp;
	BYTE acc2;

	acc2=stc_accent_raw[q][4];	/* 第２アクセント */

	/* 第２アクセントありなら、高くついて第２アクセントの滝で落ちる。*/
	if(acc2!=0xFF){
		/* 第２アクセントがあれば、後語の滝を変える。*/
		if(acc2==0){ ACC000H(q); }else{ ACC0003(q,acc2); }
	}

	/* 第２アクセントが未定義のとき。*/
	if(stc_accent_raw[q][0]==0){
		/* 平板型ならば、１拍目で落ちる。*/
		ACC0001(q);
	}else{
		/* 平板型以外ならば、高く付いて第１アクセントの瀧で落ちる。*/
		qp=phrase_ptr[q];
		if(accent0[qp]==1){ accent0[qp]=2; }
	}
}

