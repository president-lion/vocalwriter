/*========== ACC222Z(q) ===================================================
	機能：ｑ番目の要素は、１０１型の結合をする

	　即ち、高く付いて、自身の滝で落ちる

	解説：「日本語解析」＋「システム」では、問題ないが、
		「日本語」＋「解析システム」の時、「解析システム」の結合規則が
		問題になる。「解析システム」の結合規則は「解析」、「システム」の
		結合規則とは異なり、多分、前を平板化し高く付いて自分の滝で落ちると
		思われる。
  ==========================================================================*/
void ACC222Z(q) register integer_16 q; {
	register integer_16 qp;
	qp=phrase_ptr[q];
	if(accent0[qp]==1){ accent0[qp]=2; }
}

