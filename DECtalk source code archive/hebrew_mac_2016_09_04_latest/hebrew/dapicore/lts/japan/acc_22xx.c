/*========== ACC22PO(p,q) =============================================
	機能：「お」がついたときのアクセントを決定する

	いずれの場合も「お」はひくくなる。

	お＋形容詞：後続要素は高く付き、平板化する。
	お＋動詞　：後続要素は高く付き、平板化する。
	お＋名詞　：頭高名詞のときは変化しない。
				頭高以外のときは
				第２アクセントがあれば、それを用いる。
				なければ、後続要素は高く付き、平板化する
  =====================================================================*/
void ACC22PO(p,q) integer_16 p,q; {
	integer_16 acc; register integer_16 qp,bno;

	ACC0004(p);
	qp=phrase_ptr[q];
	bno=stc_bno[q][0];
	bno=bno_tbl[bno-1];
	if(bno==pkind_verb_stem||bno==pkind_verb_sa){ goto ACC22PO_verb; }
	if(bno==pkind_adj_stem){ goto ACC22PO_adj; }

	/* 頭高ならなにもしない。*/
	if(stc_accent_raw[q][0]==1){ return; }
	/* 第２アクセントがなければ高くついて平板化する。*/
	if((acc=stc_accent_raw[q][4])==0xFF){
		ACC0005(q);
	}else{
		if(acc==0){ ACC000H(q); }else{ ACC0003(q,acc); }
	}
	if(accent0[qp]==1){ accent0[qp]=2; }
	return;
ACC22PO_verb:;
ACC22PO_adj:;
	ACC0005(q);
}

/*========== ACC2232(p,q) ======================================================
	機能：ｐ番目の要素は、ｑ番目の要素に影響して、３２型の結合をする

	  即ち、ｐ番目は平板化し、
	ｑ番目は、第２アクセントがあれば第２アクセントで、なければ頭高化する。
  ==============================================================================*/
void ACC2232(p,q) integer_16 p,q; {
	BYTE acc4;
	register integer_16 qp,ql;
	ACC000H(p);
	if((acc4=stc_accent_raw[q][4])!=0xFF){
		ACC0003(q,acc4);
		qp=phrase_ptr[q]; ql=phrase_len[q];
		if(ql>1 && accent0[qp]==1){
			accent0[qp]=2;
		}
	}else{
		ACC0001(q);
	}
}

/*========== ACC2233(p,q) ============================================
	機能：ｐ番目の要素は、ｑ番目の要素に影響して、３３型の結合をする

	  即ち、ｐ番目は平板になり、ｑ番目は高く付いて、自身の滝で落ちる
  ====================================================================*/
void ACC2233(p,q) integer_16 p,q; {
	register integer_16 qp;
	qp=phrase_ptr[q];
	ACC000H(p);
	if(accent0[qp]==1){ accent0[qp]=2; }
}

/*========== ACC2234(p,q) ============================================
	機能：ｐ番目の要素は、ｑ番目の要素に影響して、３４型の結合をする

	  即ち、ｑ番目が２桁以上の数字の時は結合しない。
	ｑ番目が１桁の数字の時は、ｐ番目が頭高の時は、ｑ番目は低く付く。
	ｐ番目が頭高以外の時は、ｑ番目は高く付く。

	（例）「第１」は結合し「１」は低く付く。「第２５」は非結合。
		　「図１」は結合し「１」は高く付く。「図２５」は非結合。
		　「表１」は結合し「１」は高く付く。「表２５」は非結合。
		　ｐ番目の要素は、とりあえず、この３種ぐらいであろう。

			この処理はACC2800()で行う。
  ====================================================================*/

/*========== ACC2236(p,q) ============================================
	機能：ｐ番目の要素は、ｑ番目の要素に影響して、３６型の結合をする

	  即ち、ｐ番目もｑ番目も独自のアクセントを守る。
		（例）各
  ====================================================================*/

/*========== ACC2237(p,q) ============================================
	機能：ｐ番目の要素は、ｑ番目の要素に影響して、３７型の結合をする

	  即ち、ｐ番目は独自のアクセントを守り、ｑ番目は低くつく。
		（例）どんな
ACC2237(p,q) integer_16 p,q; { ACC0004(q); }
  ====================================================================*/

/*========== ACC2239(p,q) ============================================
	機能：ｐ番目の要素は、ｑ番目の要素に影響して、３９型の結合をする

	  即ち、ｐ番目の最終拍が高いときは、ｑ番目は第１拍目が高くなる。

		（例）の（格助詞）
  ====================================================================*/
void ACC2239(p,q) integer_16 p,q; {
	register integer_16 qp;
	if(accent0[phrase_ptr[p]+phrase_len[p]-1]!=1){
		qp=phrase_ptr[q];
		if(accent0[qp]==1){ accent0[qp]=2; }
	}
}

